const fs = require('fs');
const path = require('path');

const API_BASE = 'https://pokeapi.co/api/v2';
const LIMIT = 1025;
const OUT = path.join(__dirname, '..', 'src', 'data', 'pokemonNamesEs.ts');

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

async function main() {
  console.log(`Fetching pokemon list (limit=${LIMIT})...`);
  const list = await fetchJson(`${API_BASE}/pokemon?limit=${LIMIT}`);

  const entries = [];
  const total = list.results.length;

  for (let i = 0; i < total; i++) {
    const r = list.results[i];
    const id = parseInt(r.url.split('/').filter(Boolean).pop(), 10);
    const enName = r.name;

    if ((i + 1) % 50 === 0 || i === total - 1) {
      console.log(`  Processing ${i + 1}/${total}...`);
    }

    try {
      const species = await fetchJson(`${API_BASE}/pokemon-species/${id}`);
      let esName = enName;
      for (const n of species.names) {
        if (n.language.name === 'es') {
          esName = n.name;
          break;
        }
      }
      entries.push({ en: enName, es: esName, id });
    } catch (err) {
      console.warn(`  Warning: failed species ${id} (${enName}): ${err.message}`);
      entries.push({ en: enName, es: enName, id });
    }
  }

  entries.sort((a, b) => a.id - b.id);

  const lines = [];
  lines.push('// Auto-generated by scripts/generate-pokemon-names.js');
  lines.push('// Do not edit manually.');
  lines.push('');
  lines.push('export const POKEMON_NAMES_ES: Record<string, string> = {');

  for (const e of entries) {
    const safeEs = e.es.replace(/'/g, "\\'");
    lines.push(`  '${e.en}': '${safeEs}',`);
  }

  lines.push('};');
  lines.push('');

  const reverseEntries = entries.filter(e => e.en !== e.es.toLowerCase());
  lines.push('const _REVERSE: Record<string, string> = {');

  for (const e of entries) {
    const safeEs = e.es.toLowerCase().replace(/'/g, "\\'");
    const safeEn = e.en.replace(/'/g, "\\'");
    if (safeEs !== safeEn) {
      lines.push(`  '${safeEs}': '${safeEn}',`);
    }
  }

  lines.push('};');
  lines.push('');
  lines.push('export function resolveEnglishName(input: string): string {');
  lines.push('  const key = input.toLowerCase().trim();');
  lines.push('  return _REVERSE[key] ?? key;');
  lines.push('}');
  lines.push('');

  fs.writeFileSync(OUT, lines.join('\n'), 'utf-8');
  console.log(`\nDone! Wrote ${entries.length} entries to ${OUT}`);
  console.log(`  ${reverseEntries.length} Pokemon have different Spanish names.`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
